// Generates public/js/config.js from environment variables (or a local .env file).
// Only PUBLIC values go in here: the project URL and the anon/publishable key.
// Never put a service-role / secret key in this project.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function loadDotenv() {
  const p = resolve(root, '.env');
  if (!existsSync(p)) return {};
  const out = {};
  for (const line of readFileSync(p, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !line.trim().startsWith('#')) out[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
  return out;
}

const env = { ...loadDotenv(), ...process.env };
const url = (env.SUPABASE_URL || '').trim().replace(/\/+$/, '');
const key = (env.SUPABASE_ANON_KEY || env.SUPABASE_PUBLISHABLE_KEY || '').trim();

function isServiceRole(k) {
  if (k.startsWith('sb_secret_')) return true;
  const parts = k.split('.');
  if (parts.length !== 3) return false;
  try {
    return JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8')).role === 'service_role';
  } catch {
    return false;
  }
}

if (key && isServiceRole(key)) {
  console.error('\n✖ That looks like a SECRET (service-role) key. Refusing to put it in frontend code.');
  console.error('  Use the public "anon" / "publishable" key instead.\n');
  process.exit(1);
}

const out = resolve(root, 'public/js/config.js');

// No env vars on this machine? Keep the values already saved in public/js/config.js
// (they are public values, safe to keep in the repo) instead of blanking them.
if (!url || !key) {
  if (existsSync(out)) {
    const prev = readFileSync(out, 'utf8');
    const u = (prev.match(/"supabaseUrl":\s*"([^"]+)"/) || [])[1];
    const k = (prev.match(/"supabaseKey":\s*"([^"]+)"/) || [])[1];
    if (u && k) {
      if (isServiceRole(k)) { console.error('\n✖ public/js/config.js contains a SECRET key. Remove it.\n'); process.exit(1); }
      console.log(`✓ using the values already in public/js/config.js (connected to ${u})`);
      process.exit(0);
    }
  }
  console.warn('\n⚠ SUPABASE_URL / SUPABASE_ANON_KEY are not set — the site will build, but show a "not connected" notice.\n');
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/build-config.mjs — public values only.\nwindow.LMC_CONFIG = Object.freeze(${JSON.stringify({ supabaseUrl: url, supabaseKey: key }, null, 2)});\n`,
);
console.log(`✓ wrote public/js/config.js (${url && key ? 'connected to ' + url : 'NOT connected'})`);
